P2P_PORTS=("6881:6889" "6969" "1337" "51413" "2710" "2711")

# Chains
IR_CHAIN="VPN_BLOCK_IR"
P2P_CHAIN="VPN_BLOCK_P2P"
ADS_IP="10.99.99.99"

fw() {
  case "$1" in
    -C) /sbin/iptables -w 5 "$@" 2>/dev/null ;;
    *)  /sbin/iptables -w 5 "$@" 2>/dev/null || true ;;
  esac
}

apply_ir() {
  # ipset: همه رنج‌ها در یک set (سریع — به‌جای ۸۳۴ قانون، فقط ۲ قانون)
  /sbin/ipset create vpn_ir hash:net -exist
  /sbin/ipset flush vpn_ir
  printf 'add vpn_ir %s\n' "${IR_RANGES[@]}" | /sbin/ipset restore -exist
  fw -N "$IR_CHAIN" 2>/dev/null || true
  fw -F "$IR_CHAIN"
  for pool in "${POOLS[@]}"; do
    fw -C FORWARD -s "$pool" -j "$IR_CHAIN" 2>/dev/null || fw -I FORWARD -s "$pool" -j "$IR_CHAIN"
  done
  fw -A "$IR_CHAIN" -m set --match-set vpn_ir dst -j DROP
}

remove_ir() {
  for pool in "${POOLS[@]}"; do
    while fw -C FORWARD -s "$pool" -j "$IR_CHAIN" 2>/dev/null; do
      fw -D FORWARD -s "$pool" -j "$IR_CHAIN"
    done
  done
  fw -F "$IR_CHAIN" 2>/dev/null || true
  fw -X "$IR_CHAIN" 2>/dev/null || true
  /sbin/ipset destroy vpn_ir 2>/dev/null || true
}

apply_p2p() {
  fw -N "$P2P_CHAIN" 2>/dev/null || true
  fw -F "$P2P_CHAIN"
  for pool in "${POOLS[@]}"; do
    fw -C FORWARD -s "$pool" -j "$P2P_CHAIN" 2>/dev/null || fw -I FORWARD -s "$pool" -j "$P2P_CHAIN"
  done
  for port in "${P2P_PORTS[@]}"; do
    fw -A "$P2P_CHAIN" -p tcp --dport "$port" -j DROP
    fw -A "$P2P_CHAIN" -p udp --dport "$port" -j DROP
  done
  # بلاک لینک‌های magnet/DHT معمول (udp random هم از tracker میاد — بستن 6881-6889 کافیه برای اکثراً)
  fw -A "$P2P_CHAIN" -p udp --dport 1337 -j DROP
}

remove_p2p() {
  fw -F "$P2P_CHAIN" 2>/dev/null || true
  fw -X "$P2P_CHAIN" 2>/dev/null || true
  for pool in "${POOLS[@]}"; do
    while fw -C FORWARD -s "$pool" -j "$P2P_CHAIN" 2>/dev/null; do
      fw -D FORWARD -s "$pool" -j "$P2P_CHAIN"
    done
  done
}

apply_ads() {
  bash /root/yt-adblock.sh on
}

remove_ads() {
  bash /root/yt-adblock.sh off
}

case "$WHAT" in
  ir)  [ "$STATE" = "on" ] && apply_ir  || remove_ir ;;
  p2p) [ "$STATE" = "on" ] && apply_p2p || remove_p2p ;;
  ads) [ "$STATE" = "on" ] && apply_ads || remove_ads ;;
  *) echo "usage: $0 {ir|p2p|ads} {on|off}"; exit 1 ;;
esac
echo "done: $WHAT $STATE"
